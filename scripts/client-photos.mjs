/**
 * client-photos.mjs — Integrate the client-provided service illustrations into
 * branded artboards used by the site.
 *
 * The client files are square 3D renders with a checkerboard "transparency"
 * baked into the pixels (RGB, no alpha). This script:
 *   1. Keys the checkerboard out via flood-fill from the image borders
 *      (neutral, light pixels connected to the edge — interior highlights and
 *      the blue glows are preserved), eroding 1px to remove the antialias halo.
 *   2. Composites the cut-out onto a brand artboard (navy gradient, subtle
 *      technical grid, soft glow, amber accent bar).
 *
 * Inputs (kept untouched — originals live in the same folder):
 *   public/images/services/cambio de neumaticos.webp   -> tire-change
 *   public/images/services/arranque de emergencia.webp -> jump-start
 *   public/images/services/entrega de combustible.webp -> fuel-delivery
 *   public/images/services/servicio de frenos.webp     -> brake-service
 *   public/images/services/Refeers.webp                -> reefer-maintenance
 *   public/images/services/cambio de aceite.webp       -> oil-change-service
 *
 * Output (replaces the placeholder icon cards generated by service-icons.mjs):
 *   public/images/services/<slug>.webp        800×800  — grid tiles, thumbnails, detail hero
 *   public/images/services/<slug>-wide.webp   1200×675 — 16:9 ServiceCard
 *
 * Usage: node scripts/client-photos.mjs
 */

import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const DIR = path.join(ROOT, "public", "images", "services");

const NAVY = "#1B2A5B";
const NAVY_LIGHT = "#243a7d";
const YELLOW = "#F5B301";

/** client file basename (no ext) -> canonical service slug */
const MAP = {
  "cambio de neumaticos": "tire-change",
  "arranque de emergencia": "jump-start",
  "entrega de combustible": "fuel-delivery",
  "servicio de frenos": "brake-service",
  "Refeers": "reefer-maintenance",
  "cambio de aceite": "oil-change-service",
};

/** Checkerboard = neutral & light (grays 240–255 measured on the sources). */
function isChecker(r, g, b) {
  const mx = Math.max(r, g, b);
  const mn = Math.min(r, g, b);
  return mn >= 236 && mx - mn <= 12;
}

/**
 * Remove the baked checkerboard: flood-fill from every border pixel through
 * checker-like pixels only. Interior whites/chrome stay opaque because they are
 * not connected to the border. Then erode the subject by 1px (cardinal) so the
 * antialiased rim does not leave a light fringe on the navy artboard.
 */
function keyCheckerboard(raw, W, H, C) {
  const bg = new Uint8Array(W * H);
  const stack = [];
  const tryPush = (x, y) => {
    const k = y * W + x;
    if (bg[k]) return;
    const i = k * C;
    if (isChecker(raw[i], raw[i + 1], raw[i + 2])) {
      bg[k] = 1;
      stack.push(k);
    }
  };
  for (let x = 0; x < W; x++) {
    tryPush(x, 0);
    tryPush(x, H - 1);
  }
  for (let y = 0; y < H; y++) {
    tryPush(0, y);
    tryPush(W - 1, y);
  }
  while (stack.length) {
    const k = stack.pop();
    const x = k % W;
    const y = (k / W) | 0;
    if (x > 0) tryPush(x - 1, y);
    if (x < W - 1) tryPush(x + 1, y);
    if (y > 0) tryPush(x, y - 1);
    if (y < H - 1) tryPush(x, y + 1);
  }
  // Dilate the background by 1px (cardinal) to eat the antialiased halo.
  const bg2 = new Uint8Array(W * H);
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const k = y * W + x;
      let v = bg[k];
      if (
        !v &&
        ((x > 0 && bg[k - 1]) ||
          (x < W - 1 && bg[k + 1]) ||
          (y > 0 && bg[k - W]) ||
          (y < H - 1 && bg[k + W]))
      ) {
        v = 1;
      }
      bg2[k] = v;
    }
  }
  const out = Buffer.allocUnsafe(W * H * 4);
  for (let k = 0; k < W * H; k++) {
    const i = k * C;
    const q = k * 4;
    out[q] = raw[i];
    out[q + 1] = raw[i + 1];
    out[q + 2] = raw[i + 2];
    out[q + 3] = bg2[k] ? 0 : 255;
  }
  return out;
}

/** Brand artboard background: navy gradient + technical grid + soft glow. */
function artboardSvg(w, h) {
  const grid = 48;
  const glowCyan = "#5B8DEF";
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${NAVY}"/>
      <stop offset="1" stop-color="${NAVY_LIGHT}"/>
    </linearGradient>
    <radialGradient id="glow" cx="0.5" cy="0.46" r="0.62">
      <stop offset="0" stop-color="${glowCyan}" stop-opacity="0.16"/>
      <stop offset="1" stop-color="${glowCyan}" stop-opacity="0"/>
    </radialGradient>
    <pattern id="grid" width="${grid}" height="${grid}" patternUnits="userSpaceOnUse">
      <path d="M${grid} 0H0V${grid}" fill="none" stroke="#ffffff" stroke-opacity="0.05" stroke-width="1"/>
    </pattern>
  </defs>
  <rect width="${w}" height="${h}" fill="url(#bg)"/>
  <rect width="${w}" height="${h}" fill="url(#grid)"/>
  <circle cx="${w / 2}" cy="${Math.round(h * 0.46)}" r="${Math.round(Math.min(w, h) * 0.46)}" fill="url(#glow)"/>
  <rect x="0" y="${h - 8}" width="${w}" height="8" fill="${YELLOW}" opacity="0.9"/>
</svg>`;
}

/**
 * Compose the cut-out onto the artboard: subject contained in a box, centered.
 * @param {Buffer} cutout RGBA buffer of the keyed source
 * @param {number} W source width
 * @param {number} H source height
 * @param {number} w artboard width
 * @param {number} h artboard height
 * @param {number} fill subject height as fraction of artboard height
 */
async function compose(cutout, W, H, w, h, fill) {
  const bar = 8;
  const boxH = Math.round((h - bar) * fill);
  const boxW = Math.round((w - bar) * fill);
  const s = Math.min(boxW / W, boxH / H);
  const tw = Math.round(W * s);
  const th = Math.round(H * s);
  const subject = await sharp(cutout, { raw: { width: W, height: H, channels: 4 } })
    .resize(tw, th)
    .png()
    .toBuffer();
  const top = Math.round((h - bar - th) / 2);
  const left = Math.round((w - tw) / 2);
  return sharp(Buffer.from(artboardSvg(w, h)))
    .composite([{ input: subject, top, left }])
    .webp({ quality: 82, effort: 6 })
    .toBuffer();
}

async function main() {
  const files = await readdir(DIR);
  const byBase = new Map(
    files.filter((f) => f.endsWith(".webp")).map((f) => [f.replace(/\.webp$/, ""), f])
  );

  let done = 0;
  for (const [base, slug] of Object.entries(MAP)) {
    const file = byBase.get(base);
    if (!file) {
      console.warn(`⚠ missing source: ${base}.webp`);
      continue;
    }
    const src = await readFile(path.join(DIR, file));
    const meta = await sharp(src).metadata();
    const { data: raw, info } = await sharp(src)
      .removeAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true });

    const cutout = keyCheckerboard(raw, info.width, info.height, info.channels);

    const square = await compose(cutout, info.width, info.height, 800, 800, 0.78);
    await writeFile(path.join(DIR, `${slug}.webp`), square);

    const wide = await compose(cutout, info.width, info.height, 1200, 675, 0.9);
    await writeFile(path.join(DIR, `${slug}-wide.webp`), wide);

    console.log(
      `✓ ${slug}  (${meta.width}×${meta.height} → 800² + 1200×675, ` +
        `${(square.length / 1024).toFixed(0)}KB / ${(wide.length / 1024).toFixed(0)}KB)`
    );
    done++;
  }
  console.log(`\nDone: ${done}/${Object.keys(MAP).length} services rebuilt from client photos.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
